// Passo 2 na tela real, nas cópias. Nada é enviado: /api/send, /api/ladder e as execuções são abortados.
const { chromium, RENDERER } = require('./ambiente');
const OUT = process.argv[2];
const B = 'http://127.0.0.1:8841', project = RENDERER, run = '20261104-020244';
const HOOK = "window.__t = { state, studio, t, showTab, loadRun, renderHot, get hot() { return hot; }, get hotPicked() { return hotPicked; } }; if (location.hash === '#debug')";
const ok = (n, pass, d = '') => { console.log(`${pass ? 'PASSA' : 'FALHA'}  ${n}${d ? '  -> ' + d : ''}`); if (!pass) process.exitCode = 1; };
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 } })).newPage();
  const errors = []; let sent = 0;
  page.on('pageerror', e => errors.push(e.message));
  await page.route(/\/api\/(send|ladder|generate|instrument\/run|commands\/run|commands\/approve|paste|review)\b/, r => { sent++; return r.abort(); });
  await page.route(`${B}/`, async r => { const x = await r.fetch(); r.fulfill({ response: x, body: (await x.text()).replace("if (location.hash === '#debug')", HOOK) }); });
  await page.goto(`${B}/`);
  await page.waitForFunction(() => window.__t && __t.studio.status, null, { timeout: 60000 });
  await page.fill('#projectPath', project);
  await page.click('#openProject');
  await page.waitForFunction(() => __t.studio.project, null, { timeout: 60000 });
  await page.evaluate(x => __t.loadRun(x), run);
  await page.waitForFunction(() => __t.hot, null, { timeout: 120000 });
  await page.waitForTimeout(500);
  await page.evaluate(() => __t.showTab('inventory'));
  const text = () => page.evaluate(() => document.querySelector('#hotList').innerText);
  const body = await text();
  ok('sem texto antigo na lista', !/mais pesada|Mais tempo|mais de 1\.000\.000|um milhão/i.test(body));
  ok('título do ranking diz contagem e referência', /Maior contagem observada, com o tempo instrumentado como referência/.test(body));
  ok('o aviso visível diz os quatro limites', /frequência observada/.test(body) && /não o custo próprio/.test(body) && /não quer dizer que ela não rodou/.test(body) && /não observou passagens positivas/.test(body));
  const initial = await page.evaluate(() => { const b = [...document.querySelectorAll('#hotList button')].find(x => x.textContent.startsWith('Separar')); const s = document.querySelector('#hotPick');
    return { label: b.textContent, disabled: b.disabled, value: s.value, picked: __t.hotPicked, options: s.options.length, first: s.options[1].textContent, callers: /Quem chama:/.test(b.closest('.hot-sep').innerText) }; });
  ok('sem alvo automático: nada escolhido e botão desligado', initial.value === '' && initial.picked === null && initial.disabled && !initial.callers, JSON.stringify(initial));
  const order = await page.evaluate(() => [...document.querySelectorAll('#hotPick option')].slice(1).map(o => Number(o.value && __t.hot.rows.find(r => r.at === o.value).calls)));
  ok('a lista segue as chamadas', order.every((c, i) => i === 0 || order[i - 1] >= c));
  const ranked = await page.evaluate(() => __t.hot.rows.slice(0, 20).every((r, i, a) => i === 0 || a[i - 1].calls >= r.calls));
  ok('o ranking segue as chamadas', ranked);
  await page.screenshot({ path: `${OUT}/passo2-sem-escolha.png`, fullPage: false });
  const choice = await page.evaluate(() => { const r = __t.hot.rows.find(x => x.symbol && (x.callers ?? []).length && (x.callers ?? []).some(c => c.calls >= x.calls * .05)); return r.at; });
  await page.selectOption('#hotPick', choice);
  await page.waitForTimeout(200);
  const after = await page.evaluate(() => { const b = [...document.querySelectorAll('#hotList button')].find(x => x.textContent.startsWith('Separar')); const s = document.querySelector('#hotPick');
    return { label: b.textContent, disabled: b.disabled, value: s.value, callers: /Quem chama:/.test(b.closest('.hot-sep').innerText) }; });
  ok('a pessoa escolhe e o botão liga', after.value === choice && !after.disabled && after.callers && /\(\d+ perguntas\)/.test(after.label), JSON.stringify(after));
  await page.screenshot({ path: `${OUT}/passo2-escolhida.png`, fullPage: false });
  ok('nenhum envio', sent === 0);
  ok('sem erro de página', errors.length === 0, errors.join(' | ').slice(0, 200));
  await browser.close();
})().catch(e => { console.error(e); process.exit(2); });
